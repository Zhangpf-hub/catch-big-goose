"""Record shipped assets, source bindings and executed acceptance evidence."""
from pathlib import Path
import json, hashlib, xml.etree.ElementTree as ET
from PIL import Image, ImageDraw, ImageFont
ROOT=Path(__file__).resolve().parents[2]
WORK=ROOT/'competitor-analysis/artifacts/competitor-replacement-20261025'
CAND=ROOT/'source-assets/models/candidates/competitor-runtime-20261025'
RES=ROOT/'projects/catch-big-goose-unity/Assets/Resources'
def read(p):return json.loads(p.read_text(encoding='utf-8-sig'))
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
themes=read(RES/'Data/themes.json')['themes']
metrics={m['id']:m for m in read(CAND/'batch-results.json')}
font=ImageFont.truetype('C:/Windows/Fonts/msyh.ttc',22)
small=ImageFont.truetype('C:/Windows/Fonts/msyh.ttc',13)
for theme in themes:
    ids=theme['items'];sheet=Image.new('RGB',(5*210,55+((len(ids)+4)//5)*230),(243,238,225));draw=ImageDraw.Draw(sheet)
    draw.text((20,15),theme['name']+' / '+str(len(ids))+' 件',font=font,fill=(43,47,43))
    for i,mid in enumerate(ids):
        x=(i%5)*210;y=55+(i//5)*230
        icon=Image.open(CAND/mid/'icon-192.png').convert('RGBA');sheet.paste(icon,(x+9,y),icon)
        draw.text((x+8,y+194),mid,font=small,fill=(43,47,43))
    sheet.save(CAND/(theme['id']+'-contact.jpg'),quality=93)
qa=read(WORK/'playtest/acceptance.json');assert qa['passed'] and qa['rounds']==15,qa['errors']
tests=ET.parse(WORK/'edit-tests-final.xml').getroot();assert tests.attrib['failed']=='0'
gallery=Image.new('RGB',(390*5,894),(244,239,225));draw=ImageDraw.Draw(gallery)
for i,theme in enumerate(themes):
    draw.text((i*390+18,13),theme['name']+' · '+str(len(theme['items']))+' 件',font=font,fill=(43,47,43))
    frame=Image.open(WORK/'playtest'/(theme['id']+'-pile.png')).convert('RGB');assert frame.size==(390,844),frame.size
    gallery.paste(frame,(i*390,50))
gallery.save(WORK/'five-scenes.jpg',quality=93)
runtime=[]
for theme in themes:
    for mid in theme['items']:
        folder=RES/'Models'/mid;materials=read(folder/'materials.json')['materials']
        runtime.append(dict(id=mid,theme=theme['id'],triangles=metrics[mid]['triangles'],materials=len(materials),
            materialMode='source-material-groups' if any(m.get('referenceMaterial') for m in materials) else 'single-atlas-mobile',
            fbxSha256=sha(folder/(mid+'.fbx')),iconSha256=sha(RES/'Icons'/(mid+'.png')),physicsSha256=sha(RES/'Physics'/(mid+'.asset'))))
retired=read(ROOT/'projects/catch-big-goose-unity/SourceAssets/BeforeCompetitorReplacement-20261025/retired-assets.json')
report=dict(passed=True,date='2026-10-25',models=runtime,themes=[dict(id=t['id'],name=t['name'],count=len(t['items'])) for t in themes],
    retiredModelCount=sum(1 for r in retired if '/Models/' in r['from'].replace('\\','/') and not r['from'].endswith('.meta')),
    sourceWeightsMatched=len(read(WORK/'weight-bindings.json')['bindings']),editTestsPassed=int(tests.attrib['passed']),
    playtestRounds=qa['rounds'],playtestChecks=len(qa['checks']),playtestResolution=[390,844],
    releaseSha256=sha(ROOT/'projects/catch-big-goose-unity/Builds/Windows/catch-big-goose.exe'),
    limitations=['Windows player with mobile profile; not an Android/iPhone FPS test.',
        '59 items use flattened mobile albedo materials; original shader programs were not recovered.',
        '21 toy items retain separately validated source material groups and project MatCap/glass shaders.',
        'Existing containers, backgrounds and three system goose targets are retained; mascot assets are unchanged.',
        'Only locally cached ordinary props are included; source weights are mapped by exact name to the cached subset.',
        'Existing WeChat build has not been regenerated by this delivery.'])
(WORK/'delivery.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf8')
print(json.dumps({k:v for k,v in report.items() if k not in ['models','limitations']},ensure_ascii=False))
